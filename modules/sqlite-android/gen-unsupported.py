#!/usr/bin/env python3
# Generates UnsupportedJdbc.scala: for each java.sql interface the Android driver implements,
# an abstract class whose every abstract method throws SQLFeatureNotSupportedException. The
# driver extends these and overrides what it supports, so the hundreds of JDBC methods it does
# not (ResultSet alone has ~190) are written down once, by a program, and say so when called.
#
#   modules/sqlite-android/gen-unsupported.py "$(cs java-home --jvm temurin:21)"
#
# Signatures come from `javap -public` on the JDK's java.sql. Only abstract methods: defaults
# and statics are inherited as they are.
import re, subprocess, sys, pathlib

jdk = sys.argv[1]
here = pathlib.Path(__file__).resolve().parent
out = here / "src/main/scala/thicket/sqlite/android/UnsupportedJdbc.scala"

# class name, interface, parent (None: extends the interface directly), extra interfaces whose
# abstract methods must also be stubbed (javap lists declared methods only).
classes = [
    ("UnsupportedDriver", "java.sql.Driver", None, []),
    ("UnsupportedConnection", "java.sql.Connection", None, ["java.sql.Wrapper"]),
    ("UnsupportedStatement", "java.sql.Statement", None, ["java.sql.Wrapper"]),
    ("UnsupportedPreparedStatement", "java.sql.PreparedStatement", "UnsupportedStatement", []),
    ("UnsupportedResultSet", "java.sql.ResultSet", None, ["java.sql.Wrapper"]),
    ("UnsupportedResultSetMetaData", "java.sql.ResultSetMetaData", None, ["java.sql.Wrapper"]),
]

PRIM = {"int": "Int", "long": "Long", "boolean": "Boolean", "double": "Double", "float": "Float",
        "short": "Short", "byte": "Byte", "void": "Unit", "char": "Char"}

def scala_type(t):
    t = t.strip()
    if t.endswith("..."):
        return "Array[" + scala_type(t[:-3]) + "]"
    if t.endswith("[]"):
        return "Array[" + scala_type(t[:-2]) + "]"
    if t in PRIM:
        return PRIM[t]
    m = re.match(r"^([\w.$]+)<(.*)>$", t)
    if m:
        return scala_type(m.group(1)) + "[" + ", ".join(scala_type(a) for a in split_args(m.group(2))) + "]"
    if t == "?":
        return "?"
    if t.startswith("? extends "):
        return "? <: " + scala_type(t[len("? extends "):])
    if t == "java.lang.Object":
        return "Object"
    if t.startswith("java.lang.") and t.count(".") == 2:
        return t[len("java.lang."):]
    return "_root_." + t if "." in t else t

def split_args(s):
    args, depth, cur = [], 0, ""
    for ch in s:
        if ch == "<": depth += 1
        if ch == ">": depth -= 1
        if ch == "," and depth == 0:
            args.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur)
    return [a.strip() for a in args]

def methods(iface):
    text = subprocess.run([f"{jdk}/bin/javap", "-public", iface], capture_output=True, text=True, check=True).stdout
    ms = []
    for line in text.splitlines():
        line = line.strip()
        if not line.startswith("public abstract ") or "(" not in line:
            continue
        sig = re.sub(r"\s+throws .*;$", ";", line)[len("public abstract "):].rstrip(";")
        tparams = ""
        m = re.match(r"^<(\w+)> (.*)$", sig)
        if m:
            tparams, sig = m.group(1), m.group(2)
        head, args = sig.split("(", 1)
        args = args.rstrip(")")
        ret, name = head.rsplit(" ", 1)
        ms.append((name, tparams, [scala_type(a) for a in split_args(args)], scala_type(ret)))
    return ms

lines = [
    open(here.parent / "core/shared/src/main/scala/thicket/core/Element.scala").read().split("*/", 1)[0] + "*/",
    "",
    "// GENERATED by modules/sqlite-android/gen-unsupported.py from the JDK's java.sql. Do not edit; regenerate.",
    "",
    "package thicket.sqlite.android",
    "",
    "import java.sql.SQLFeatureNotSupportedException",
    "",
    "private def unsupported(what: String): Nothing =",
    '  throw new SQLFeatureNotSupportedException(s"$what is not supported by the Android SQLite driver")',
]
for cls, iface, parent, extra in classes:
    seen = set()
    body = []
    for i in [iface] + extra:
        for name, tp, args, ret in methods(i):
            key = (name, tuple(args))
            if key in seen:
                continue
            seen.add(key)
            params = ", ".join(f"p{n}: {a}" for n, a in enumerate(args))
            tps = f"[{tp}]" if tp else ""
            body.append(f'  def {name}{tps}({params}): {ret} = unsupported("{iface.split(".")[-1]}.{name}")')
    ext = f"{parent} with {iface}" if parent else iface
    lines += ["", f"abstract class {cls} extends {ext} {{", ""] + body + ["", "}"]
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
