package thicket.sqlite.android

import android.database.{Cursor, DatabaseUtils, MatrixCursor}
import android.database.sqlite.{SQLiteCursor, SQLiteCursorDriver, SQLiteDatabase, SQLiteProgram, SQLiteQuery}
import thicket.sqlite.SqliteDriver

import java.sql.{Connection, ResultSet, ResultSetMetaData, SQLException, Statement}
import java.util.Properties

/** SQLite on Android through JDBC, over the platform's own `android.database.sqlite` (`docs/16-device-services.md`
  * §16.5): no SQLite of its own in the APK, and no maintained third-party driver to depend on.
  *
  * It implements the subset `thicket.sqlite.Sqlite` documents and `JdbcConformance` checks; everything else throws
  * `SQLFeatureNotSupportedException` (see `UnsupportedJdbc.scala`).
  *
  * Android ties a transaction to the thread that began it, so a connection with auto-commit off must be used from one
  * thread — which JDBC code does anyway.
  */
object AndroidSqlite {

  given driver: SqliteDriver = SqliteDriver.fromJdbc(AndroidSqliteDriver())

}

/** Turns Android's unchecked `android.database.SQLException` (and a bad bind's `IllegalArgumentException`) into JDBC's
  * checked `java.sql.SQLException`, which is what JDBC callers catch.
  */
private def jdbc[A](body: => A): A =
  try body
  catch {
    case e: android.database.SQLException => throw new SQLException(e.getMessage, e)
    case e: IllegalArgumentException      => throw new SQLException(e.getMessage, e)
  }

final class AndroidSqliteDriver extends UnsupportedDriver {

  private val prefix = "jdbc:sqlite:"

  override def acceptsURL(url: String): Boolean = url != null && url.startsWith(prefix)

  // JDBC's convention: null for a URL this driver does not handle, so DriverManager can try the next.
  override def connect(
    url:  String,
    info: Properties
  ): Connection =
    if !acceptsURL(url) then null
    else
      jdbc {
        url.substring(prefix.length) match {
          case ":memory:" | "" => AndroidConnection(SQLiteDatabase.create(null))
          case path            => AndroidConnection(SQLiteDatabase.openOrCreateDatabase(path, null))
        }
      }

  override def getMajorVersion(): Int = 0
  override def getMinorVersion(): Int = 1
  override def jdbcCompliant():   Boolean = false

}

final class AndroidConnection(private[android] val db: SQLiteDatabase) extends UnsupportedConnection {

  private var autoCommit = true

  override def createStatement(): Statement = AndroidStatement(this)

  override def prepareStatement(sql: String): java.sql.PreparedStatement =
    AndroidPreparedStatement(this, sql, generatedKeys = false)

  override def prepareStatement(
    sql:               String,
    autoGeneratedKeys: Int
  ): java.sql.PreparedStatement =
    AndroidPreparedStatement(this, sql, generatedKeys = autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS)

  // SQLite can only return the rowid, whichever columns are named; drivers for other databases use these to ask for
  // several. Magnum calls them for databases other than SQLite, so they are here for completeness.
  override def prepareStatement(
    sql:           String,
    columnIndexes: Array[Int]
  ): java.sql.PreparedStatement = AndroidPreparedStatement(this, sql, generatedKeys = true)

  override def prepareStatement(
    sql:         String,
    columnNames: Array[String]
  ): java.sql.PreparedStatement = AndroidPreparedStatement(this, sql, generatedKeys = true)

  override def getAutoCommit(): Boolean = autoCommit

  override def setAutoCommit(on: Boolean): Unit =
    jdbc {
      if on != autoCommit then {
        if on then {
          db.setTransactionSuccessful()
          db.endTransaction()
        } else db.beginTransaction()
        autoCommit = on
      }
    }

  override def commit(): Unit =
    jdbc {
      if !autoCommit then {
        db.setTransactionSuccessful()
        db.endTransaction()
        db.beginTransaction()
      }
    }

  override def rollback(): Unit =
    jdbc {
      if !autoCommit then {
        db.endTransaction()
        db.beginTransaction()
      }
    }

  // An open transaction is rolled back, as JDBC leaves it to the driver and SQLite does on close.
  override def close(): Unit =
    jdbc {
      if db.isOpen then {
        if !autoCommit && db.inTransaction then db.endTransaction()
        db.close()
      }
    }

  override def isClosed(): Boolean = !db.isOpen

  /** The rowid of this connection's last insert. The database is opened without write-ahead logging, so it has one
    * connection underneath and this is the same session the insert ran in.
    */
  private[android] def lastInsertRowid(): Long = {
    val s = db.compileStatement("select last_insert_rowid()")
    try s.simpleQueryForLong()
    finally s.close()
  }

  /** A query with typed parameters. `rawQuery` binds strings only, so the parameters are bound on the `SQLiteQuery`
    * itself, which a `CursorFactory` is handed before the query runs.
    */
  private[android] def query(
    sql:    String,
    params: Seq[Param]
  ): Cursor =
    jdbc {
      val factory = new SQLiteDatabase.CursorFactory {
        def newCursor(
          d:      SQLiteDatabase,
          driver: SQLiteCursorDriver,
          table:  String,
          q:      SQLiteQuery
        ): Cursor = {
          Param.bindAll(q, params)
          new SQLiteCursor(driver, table, q)
        }
      }
      db.rawQueryWithFactory(factory, sql, null, null)
    }

}

/** A bound parameter, kept so it can be bound again: on the compiled statement (to check the index at once, as JDBC
  * does) and on the query that actually runs.
  */
private[android] enum Param {

  case Text(v: String)
  case Integer(v: Long)
  case Real(v: Double)
  case Blob(v: Array[Byte])
  case Null

}

private[android] object Param {

  def bind(
    p:     SQLiteProgram,
    index: Int,
    v:     Param
  ): Unit =
    v match {
      case Param.Text(s)    => p.bindString(index, s)
      case Param.Integer(l) => p.bindLong(index, l)
      case Param.Real(d)    => p.bindDouble(index, d)
      case Param.Blob(b)    => p.bindBlob(index, b)
      case Param.Null       => p.bindNull(index)
    }

  def bindAll(
    p:      SQLiteProgram,
    params: Seq[Param]
  ): Unit =
    params.zipWithIndex.foreach(
      (
        v,
        i
      ) => if v != null then bind(p, i + 1, v)
    )

}

class AndroidStatement(conn: AndroidConnection) extends UnsupportedStatement {

  private var closed = false
  private var current: ResultSet = null
  private var updateCount = -1
  protected var generated: ResultSet = null

  protected def check(): Unit = if closed || conn.isClosed() then throw new SQLException("statement is closed")

  override def executeQuery(sql: String): ResultSet = {
    check()
    current = AndroidResultSet(conn.query(sql, Nil))
    updateCount = -1
    current
  }

  override def executeUpdate(sql: String): Int = executeUpdate(sql, Statement.NO_GENERATED_KEYS)

  override def executeUpdate(
    sql:               String,
    autoGeneratedKeys: Int
  ): Int =
    jdbc {
      check()
      val s = conn.db.compileStatement(sql)
      val n =
        try s.executeUpdateDelete()
        finally s.close()
      if autoGeneratedKeys == Statement.RETURN_GENERATED_KEYS then generated = keys()
      current = null
      updateCount = n
      n
    }

  /** `true` for a statement that returns rows: Android's own classification, plus `WITH`, which it calls "other". */
  override def execute(sql: String): Boolean =
    if returnsRows(sql) then {
      executeQuery(sql)
      true
    } else {
      executeUpdate(sql)
      false
    }

  override def getResultSet():   ResultSet = current
  override def getUpdateCount(): Int = updateCount
  override def getMoreResults(): Boolean = false

  // A hint, which a cursor over a local database has no use for: it reads rows as it is moved.
  override def setFetchSize(rows: Int): Unit = ()
  override def getFetchSize():          Int = 0

  override def getGeneratedKeys(): ResultSet =
    Option(generated).getOrElse(AndroidResultSet(MatrixCursor(Array("last_insert_rowid()"))))

  override def getConnection(): Connection = conn

  override def close(): Unit = {
    closed = true
    Option(current).foreach(_.close())
  }

  override def isClosed(): Boolean = closed

  protected def keys(): ResultSet = {
    val c = MatrixCursor(Array("last_insert_rowid()"))
    c.addRow(Array[AnyRef](java.lang.Long.valueOf(conn.lastInsertRowid())))
    AndroidResultSet(c)
  }

  protected def returnsRows(sql: String): Boolean =
    DatabaseUtils.getSqlStatementType(sql) == DatabaseUtils.STATEMENT_SELECT ||
      sql.trim.toLowerCase.startsWith("with")

}

/** Compiled when it is created, so invalid SQL fails at `prepareStatement` and a parameter index that does not exist
  * fails at the `set` call, as JDBC drivers do.
  */
final class AndroidPreparedStatement(
  conn:          AndroidConnection,
  sql:           String,
  generatedKeys: Boolean
) extends UnsupportedPreparedStatement {

  private val compiled = jdbc(conn.db.compileStatement(sql))
  private var params = Vector.empty[Param]
  private var closed = false
  private var current:   ResultSet = null
  private var generated: ResultSet = null

  private def set(
    index: Int,
    v:     Param
  ): Unit =
    jdbc {
      if closed then throw new SQLException("statement is closed")
      Param.bind(compiled, index, v)
      if params.length < index then params = params.padTo(index, null)
      params = params.updated(index - 1, v)
    }

  override def setString(
    i: Int,
    v: String
  ): Unit = set(i, if v == null then Param.Null else Param.Text(v))
  override def setInt(
    i: Int,
    v: Int
  ): Unit = set(i, Param.Integer(v.toLong))
  override def setLong(
    i: Int,
    v: Long
  ): Unit = set(i, Param.Integer(v))
  override def setShort(
    i: Int,
    v: Short
  ): Unit = set(i, Param.Integer(v.toLong))
  override def setBoolean(
    i: Int,
    v: Boolean
  ): Unit = set(i, Param.Integer(if v then 1L else 0L))
  override def setDouble(
    i: Int,
    v: Double
  ): Unit = set(i, Param.Real(v))
  override def setFloat(
    i: Int,
    v: Float
  ): Unit = set(i, Param.Real(v.toDouble))
  override def setBytes(
    i: Int,
    v: Array[Byte]
  ): Unit = set(i, if v == null then Param.Null else Param.Blob(v))
  override def setNull(
    i:       Int,
    sqlType: Int
  ): Unit = set(i, Param.Null)

  override def clearParameters(): Unit = {
    compiled.clearBindings()
    params = Vector.empty
  }

  /** The common Java types, as `setObject` is used by libraries that map an `Any`; anything else is unsupported rather
    * than stored as its `toString`.
    */
  override def setObject(
    i: Int,
    v: Object
  ): Unit =
    v match {
      case null => set(i, Param.Null)
      case s:     String            => set(i, Param.Text(s))
      case n:     java.lang.Long    => set(i, Param.Integer(n))
      case n:     java.lang.Integer => set(i, Param.Integer(n.toLong))
      case n:     java.lang.Short   => set(i, Param.Integer(n.toLong))
      case n:     java.lang.Byte    => set(i, Param.Integer(n.toLong))
      case b:     java.lang.Boolean => set(i, Param.Integer(if b then 1L else 0L))
      case d:     java.lang.Double  => set(i, Param.Real(d))
      case f:     java.lang.Float   => set(i, Param.Real(f.toDouble))
      case bytes: Array[Byte]       => set(i, Param.Blob(bytes))
      case other =>
        throw new java.sql.SQLFeatureNotSupportedException(s"setObject with a ${other.getClass.getName}")
    }

  override def setFetchSize(rows: Int): Unit = ()
  override def getFetchSize():          Int = 0

  private var batch = Vector.empty[Vector[Param]]

  /** Batches, as Magnum's `insertAll`, `updateAll` and `deleteAll` use: each set of parameters is run in turn on the
    * compiled statement. Not one transaction unless the caller made one, as JDBC specifies.
    */
  override def addBatch(): Unit = {
    if closed then throw new SQLException("statement is closed")
    batch = batch :+ params
  }

  override def clearBatch(): Unit = batch = Vector.empty

  override def executeBatch(): Array[Int] =
    jdbc {
      if closed then throw new SQLException("statement is closed")
      try
        batch.map { ps =>
          compiled.clearBindings()
          Param.bindAll(compiled, ps)
          compiled.executeUpdateDelete()
        }.toArray
      finally {
        batch = Vector.empty
        compiled.clearBindings()
        Param.bindAll(compiled, params)
      }
    }

  override def executeQuery(): ResultSet = {
    if closed then throw new SQLException("statement is closed")
    current = AndroidResultSet(conn.query(sql, params))
    current
  }

  override def executeUpdate(): Int =
    jdbc {
      if closed then throw new SQLException("statement is closed")
      val n = compiled.executeUpdateDelete()
      if generatedKeys then {
        val c = MatrixCursor(Array("last_insert_rowid()"))
        c.addRow(Array[AnyRef](java.lang.Long.valueOf(conn.lastInsertRowid())))
        generated = AndroidResultSet(c)
      }
      n
    }

  override def execute(): Boolean =
    if DatabaseUtils.getSqlStatementType(sql) == DatabaseUtils.STATEMENT_SELECT ||
      sql.trim.toLowerCase.startsWith("with")
    then {
      executeQuery()
      true
    } else {
      executeUpdate()
      false
    }

  override def getGeneratedKeys(): ResultSet =
    Option(generated).getOrElse(AndroidResultSet(MatrixCursor(Array("last_insert_rowid()"))))

  override def getResultSet():  ResultSet = current
  override def getConnection(): Connection = conn

  override def close(): Unit =
    if !closed then {
      closed = true
      Option(current).foreach(_.close())
      compiled.close()
    }

  override def isClosed(): Boolean = closed

}

/** A `Cursor` read the JDBC way: 1-based columns, labels matched ignoring case, `wasNull` after each get. */
final class AndroidResultSet(cursor: Cursor) extends UnsupportedResultSet {

  private var lastNull = false

  override def next(): Boolean = jdbc(cursor.moveToNext())

  override def close():    Unit = cursor.close()
  override def isClosed(): Boolean = cursor.isClosed

  override def wasNull(): Boolean = lastNull

  override def findColumn(label: String): Int =
    (0 until cursor.getColumnCount).find(i => cursor.getColumnName(i).equalsIgnoreCase(label)).map(_ + 1).getOrElse {
      throw new SQLException(s"no column '$label'")
    }

  private def col(i: Int): Int = {
    if i < 1 || i > cursor.getColumnCount then
      throw new SQLException(s"column $i out of range 1..${cursor.getColumnCount}")
    lastNull = jdbc(cursor.isNull(i - 1))
    i - 1
  }

  override def getString(i:  Int): String = { val c = col(i); if lastNull then null else jdbc(cursor.getString(c)) }
  override def getInt(i:     Int): Int = { val c = col(i); if lastNull then 0 else jdbc(cursor.getInt(c)) }
  override def getLong(i:    Int): Long = { val c = col(i); if lastNull then 0L else jdbc(cursor.getLong(c)) }
  override def getShort(i:   Int): Short = { val c = col(i); if lastNull then 0 else jdbc(cursor.getShort(c)) }
  override def getDouble(i:  Int): Double = { val c = col(i); if lastNull then 0.0 else jdbc(cursor.getDouble(c)) }
  override def getFloat(i:   Int): Float = { val c = col(i); if lastNull then 0f else jdbc(cursor.getFloat(c)) }
  override def getBoolean(i: Int): Boolean = getLong(i) != 0L
  override def getBytes(i:   Int): Array[Byte] = { val c = col(i); if lastNull then null else jdbc(cursor.getBlob(c)) }

  override def getString(l:  String): String = getString(findColumn(l))
  override def getInt(l:     String): Int = getInt(findColumn(l))
  override def getLong(l:    String): Long = getLong(findColumn(l))
  override def getShort(l:   String): Short = getShort(findColumn(l))
  override def getDouble(l:  String): Double = getDouble(findColumn(l))
  override def getFloat(l:   String): Float = getFloat(findColumn(l))
  override def getBoolean(l: String): Boolean = getBoolean(findColumn(l))
  override def getBytes(l:   String): Array[Byte] = getBytes(findColumn(l))

  /** The value as SQLite stores it: `Long`, `Double`, `String`, `Array[Byte]`, or `null`. */
  override def getObject(i: Int): Object = {
    val c = col(i)
    if lastNull then null
    else
      jdbc(cursor.getType(c)) match {
        case Cursor.FIELD_TYPE_INTEGER => java.lang.Long.valueOf(cursor.getLong(c))
        case Cursor.FIELD_TYPE_FLOAT   => java.lang.Double.valueOf(cursor.getDouble(c))
        case Cursor.FIELD_TYPE_BLOB    => cursor.getBlob(c)
        case _                         => cursor.getString(c)
      }
  }

  override def getObject(l: String): Object = getObject(findColumn(l))

  override def getMetaData(): ResultSetMetaData =
    new UnsupportedResultSetMetaData {
      override def getColumnCount():       Int = cursor.getColumnCount
      override def getColumnName(i:  Int): String = cursor.getColumnName(i - 1)
      override def getColumnLabel(i: Int): String = cursor.getColumnName(i - 1)
    }

}
